-- layout/serial.lua
-- Emit a Layout document as readable Lua source.

local util = require("layout.util")
local json = require("layout.json")
local M = {}

local function quote(s)
  local out = { '"' }
  for i = 1, #s do
    local c = s:sub(i, i)
    local b = c:byte()
    if c == '"' then out[#out + 1] = '\\"'
    elseif c == "\\" then out[#out + 1] = "\\\\"
    elseif c == "\n" then out[#out + 1] = "\\n"
    elseif c == "\r" then out[#out + 1] = "\\r"
    elseif c == "\t" then out[#out + 1] = "\\t"
    elseif b < 32 or b == 127 then out[#out + 1] = string.format("\\%03d", b)
    else out[#out + 1] = c end
  end
  out[#out + 1] = '"'
  return table.concat(out)
end

local function key_repr(k)
  if type(k) == "string" and k:match("^[%a_][%w_]*$") then return k end
  if type(k) == "number" then return "[" .. tostring(k) .. "]" end
  return "[" .. quote(tostring(k)) .. "]"
end

local function render(v, depth)
  if v == nil or v == json.null then return "nil" end
  local t = type(v)
  if t == "boolean" then return v and "true" or "false" end
  if t == "number" then return util.format_number(v) end
  if t == "string" then return quote(v) end
  if t ~= "table" then return "nil" end
  local pad = string.rep("  ", depth)
  local pad2 = string.rep("  ", depth + 1)
  local parts = {}
  if util.is_array(v) then
    for i = 1, #v do parts[#parts + 1] = pad2 .. render(v[i], depth + 1) end
  else
    local keys = util.sorted_keys(v)
    for _, k in ipairs(keys) do
      parts[#parts + 1] = pad2 .. key_repr(k) .. " = " .. render(v[k], depth + 1)
    end
  end
  if #parts == 0 then return "{}" end
  return "{\n" .. table.concat(parts, ",\n") .. "\n" .. pad .. "}"
end

function M.to_lua(v, opts)
  opts = opts or {}
  local lines = {}
  for _, h in ipairs(opts.header or {}) do lines[#lines + 1] = "-- " .. h end
  if #lines > 0 then lines[#lines + 1] = "" end
  lines[#lines + 1] = "-- Generated by Layout. The live session is authoritative."
  lines[#lines + 1] = "return " .. render(v, 0)
  return table.concat(lines, "\n") .. "\n"
end

return M
